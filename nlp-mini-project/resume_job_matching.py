print(preprocess_text(df.loc[0, "jd"])[:800])

# Preprocess the 1,000 records
print("Preprocessing resumes...")
df["clean_resume"] = df["resume"].apply(preprocess_text)

print("Preprocessing job descriptions...")
df["clean_jd"] = df["jd"].apply(preprocess_text)

print("Preprocessing completed!")

"""##  Methodology and Algorithm Selection

### TF-IDF
TF-IDF converts text documents into numerical vectors. Terms that are informative within a document receive greater importance than terms that occur across many documents.

### Cosine Similarity
Cosine similarity measures the angle between two TF-IDF vectors. A higher value indicates greater textual similarity.

### Why these methods?
TF-IDF and cosine similarity are simple, interpretable document-similarity methods and are appropriate for a small information-retrieval project. They also align closely with the NLP techniques covered in the laboratory work.

### Methodology Flow

```text
Resume + Job Description
          ↓
   Text Preprocessing
          ↓
Tokenization + Stopword Removal
          ↓
      Lemmatization
          ↓
        TF-IDF
          ↓
  Cosine Similarity
          ↓
    Matching Score
          ↓
    Resume Ranking
          ↓
 Precision@K / Recall@K
```

##  TF-IDF Representation
"""

# Build a shared TF-IDF vocabulary for resumes and job descriptions
all_text = pd.concat(
    [df["clean_resume"], df["clean_jd"]],
    ignore_index=True
)

tfidf_vectorizer = TfidfVectorizer(
    max_features=10000,
    ngram_range=(1, 2)
)

tfidf_matrix = tfidf_vectorizer.fit_transform(all_text)

n = len(df)

resume_vectors = tfidf_matrix[:n]
jd_vectors = tfidf_matrix[n:]

print("TF-IDF matrix shape:", tfidf_matrix.shape)
print("Resume vectors:", resume_vectors.shape)
print("Job-description vectors:", jd_vectors.shape)

"""##  Baseline Resume–Job Similarity

First, calculate similarity for each original resume–job pair. This gives a baseline similarity score for the labelled records.

"""

# Efficiently calculate similarity for corresponding resume-JD pairs.
# Because TF-IDF vectors are L2-normalized, their row-wise dot product
# is equivalent to cosine similarity.

pair_similarity = np.asarray(
    resume_vectors.multiply(jd_vectors).sum(axis=1)
).ravel()

df["similarity_score"] = pair_similarity
df["match_percentage"] = df["similarity_score"] * 100

