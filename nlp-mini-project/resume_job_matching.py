"""##  Final Matching Application

"""

# Final interactive matching function

def match_resumes(job_description, top_k=10):
    clean_job = preprocess_text(job_description)

    documents = df["clean_resume"].tolist() + [clean_job]

    vectorizer = TfidfVectorizer(
        max_features=10000,
        ngram_range=(1, 2)
    )

    matrix = vectorizer.fit_transform(documents)

    resume_matrix = matrix[:-1]
    job_vector = matrix[-1]

    scores = cosine_similarity(
        job_vector,
        resume_matrix
    ).ravel()

    results = df.copy()
    results["similarity_score"] = scores
    results["match_percentage"] = scores * 100

    results = results.sort_values(
        "similarity_score",
        ascending=False
    ).reset_index(drop=True)

    results["rank"] = np.arange(1, len(results) + 1)

    return results.head(top_k)

