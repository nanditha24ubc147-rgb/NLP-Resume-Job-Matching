"""##  Evaluation: Precision@K and Recall@K

For a valid information-retrieval evaluation, relevance labels must belong to the **same job-description query** being evaluated.

Therefore, instead of using the label from an unrelated job description, the evaluation below groups records by their exact job description. It evaluates only job descriptions that have enough candidate records to form a ranked list.

`Good Fit` and `Potential Fit` are treated as relevant; `No Fit` is treated as not relevant.

If the 1,000-record sample does not contain enough repeated job descriptions, the notebook will report that Precision@K/Recall@K cannot be reliably estimated from this sample rather than fabricating a metric.

"""

# Define relevance
RELEVANT_LABELS = {"Good Fit", "Potential Fit"}

eval_df = df.copy()
eval_df["relevant"] = eval_df["label"].isin(RELEVANT_LABELS)

# Calculate pairwise similarity again for evaluation
eval_df["similarity_score"] = pair_similarity

def precision_at_k(group, k):
    top_k = group.sort_values(
        "similarity_score",
        ascending=False
    ).head(k)

    return top_k["relevant"].mean()

def recall_at_k(group, k):
    total_relevant = group["relevant"].sum()

    if total_relevant == 0:
        return np.nan

    top_k = group.sort_values(
        "similarity_score",
        ascending=False
    ).head(k)

    return top_k["relevant"].sum() / total_relevant

# Evaluate only groups with at least K candidates
k_values = [5, 10]

evaluation_rows = []

for k in k_values:
    eligible_groups = [
        group for _, group in eval_df.groupby("jd")
        if len(group) >= k and group["relevant"].sum() > 0
    ]

    if len(eligible_groups) == 0:
        evaluation_rows.append({
            "K": k,
            "Precision@K": np.nan,
            "Recall@K": np.nan,
            "Eligible job descriptions": 0
        })
        continue

    precisions = [
        precision_at_k(group, k)
        for group in eligible_groups
    ]

    recalls = [
        recall_at_k(group, k)
        for group in eligible_groups
    ]

    evaluation_rows.append({
        "K": k,
        "Precision@K": np.mean(precisions),
        "Recall@K": np.mean(recalls),
        "Eligible job descriptions": len(eligible_groups)
    })

evaluation_results = pd.DataFrame(evaluation_rows)

display(evaluation_results)

if evaluation_results["Eligible job descriptions"].max() == 0:
    print(
        "No job description in the 1,000-record sample has enough "
        "candidate records for reliable Precision@K/Recall@K evaluation."
    )
    print(
        "Do not report fabricated Precision@K/Recall@K values. "
        "Use a larger sample or a separately labelled retrieval set."
    )

